#include "libft.h"

void	ft_striteri(char *s, void (*f)(unsigned int, char*))
{
	size_t	v;

	if (!s || !f)
		return ;
	v = 0;
	while (s[v])
	{
		f(v, &s[v]);
		v++;
	}
}
